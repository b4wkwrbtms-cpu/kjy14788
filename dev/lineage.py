isHan = lambda ch: bool(ch) and '가' <= ch <= '힣'

def occurs(text, nm):
    i = text.find(nm)
    while i >= 0:
        j = i + len(nm)
        before = text[i - 1] if i > 0 else ''
        after = text[j] if j < len(text) else ''
        if not isHan(before) and (not isHan(after) or any(text.startswith(p, j) for p in PART)):
            return True
        i = text.find(nm, j)
    return False

def texts_krv():
    for b in range(1, 67):
        bk = json.load(open(f'{KRV}/{b:02d}.json', encoding='utf-8'))
        for c, ch in enumerate(bk, 1):
            for v, t in enumerate(ch, 1): yield b, c, v, t

def texts_mz(src='bout'):
    import os
    for b in range(1, 67):
        d = f'{src}/{b:02d}'
        if not os.path.isdir(d): continue
        for f in sorted(os.listdir(d)):
            if not f.endswith('.json'): continue
            j = json.load(open(f'{d}/{f}', encoding='utf-8'))
            for v, t in enumerate(j['v'], 1): yield b, j['c'], v, t.replace('\n', ' ')

def scan(it, rules, cnt=None):
    out = {}
    for b, c, v, t in it:
        if b >= 40: continue          # 사용자(10-11 22:31): 신약은 빨간 밑줄 제외 — 계보가 예수님께서 완성된 지점
        names = []
        for nm, r in rules.items():
            if r['in'] is not None and not hit(r['in'], b, c, v): continue
            if hit(r['ex'], b, c, v): continue
            if occurs(t, nm): names.append(nm)
        if names:
            out.setdefault(str(b), {})[f'{c}:{v}'] = ','.join(names)
            if cnt is not None:
                for nm in names: cnt.setdefault(nm, {}).setdefault(b, 0); cnt[nm][b] += 1
    return out

def build(report=False, src='bout'):
    rules = {nm: {'in': None if r['in'] is None else [parse_ref(x) for x in r['in']], 'ex': [parse_ref(x) for x in r['ex']]} for nm, r in RULES.items()}
    cnt = {}
    k = scan(texts_krv(), rules, cnt); m = scan(texts_mz(src), rules)
    out = {'k': k, 'm': m}
    json.dump(out, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    print('lineage verses krv', sum(len(x) for x in k.values()), 'mz', sum(len(x) for x in m.values()), 'bytes', len(json.dumps(out, ensure_ascii=False, separators=(',', ':')).encode()))
    missing = [nm for nm in RULES if nm not in cnt]
    print('rules with no hit:', missing)
    if report:
        for nm in RULES:
            d = cnt.get(nm, {}); print(nm, sum(d.values()), dict(sorted(d.items())))
    return out

